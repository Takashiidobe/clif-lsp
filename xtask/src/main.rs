use std::collections::HashMap;
use std::fmt::Write;
use std::fs;
use std::path::PathBuf;

use cranelift_codegen::ir::condcodes::{FloatCC, IntCC};
use cranelift_codegen::ir::{MemFlagsData, Opcode, TrapCode, Type, types};
use cranelift_codegen::isa::CallConv;

fn doc_lines(lines: &[&str], end: usize) -> Vec<String> {
    let mut docs = Vec::new();
    for line in lines[..end].iter().rev() {
        match line.trim_start().strip_prefix("///") {
            Some(doc) => docs.push(doc.strip_prefix(' ').unwrap_or(doc).to_owned()),
            None => break,
        }
    }
    docs.reverse();
    docs
}

fn variant_docs(opcodes_rs: &str) -> HashMap<String, Vec<String>> {
    let lines: Vec<&str> = opcodes_rs.lines().collect();
    let start = lines.iter().position(|l| *l == "pub enum Opcode {").unwrap();
    let mut out = HashMap::new();
    for (i, line) in lines.iter().enumerate().skip(start + 1) {
        if *line == "}" {
            break;
        }
        let trimmed = line.trim_start();
        if trimmed.starts_with("///") || trimmed.starts_with("//") {
            continue;
        }
        let name: String = trimmed.chars().take_while(|c| c.is_alphanumeric()).collect();
        out.insert(name, doc_lines(&lines, i));
    }
    out
}

fn builder_docs(inst_builder_rs: &str) -> HashMap<String, Vec<String>> {
    let lines: Vec<&str> = inst_builder_rs.lines().collect();
    let mut out = HashMap::new();
    for (i, line) in lines.iter().enumerate() {
        let Some(rest) = line.strip_prefix("    fn ") else { continue };
        let name: String = rest.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
        let mut end = i;
        while end > 0 && lines[end - 1].trim_start().starts_with("#[") {
            end -= 1;
        }
        out.entry(name).or_insert_with(|| doc_lines(&lines, end));
    }
    out
}

fn generated(file: &str) -> String {
    let scratch = std::env::temp_dir().join(format!("clif-lsp-xtask-{}", std::process::id()));
    fs::create_dir_all(&scratch).unwrap();
    cranelift_codegen_meta::generate_rust(&[], &scratch).unwrap();
    let text = fs::read_to_string(scratch.join(file)).unwrap();
    fs::remove_dir_all(&scratch).unwrap();
    text
}

fn generate_opcodes() -> String {
    let sigs = variant_docs(&generated("opcodes.rs"));
    let long = builder_docs(&generated("inst_builder.rs"));

    let mut out = String::new();
    out.push_str("// @generated by `cargo run -p xtask -- gen-opcodes` from cranelift 0.136.2; do not edit.\n\n");
    out.push_str("use super::OpcodeInfo;\n\npub static OPCODES: &[OpcodeInfo] = &[\n");
    let mut opcodes: Vec<Opcode> = Opcode::all().to_vec();
    opcodes.sort_by_key(|o| o.to_string());
    for op in opcodes {
        let name = op.to_string();
        let variant = format!("{op:?}");
        let sig_docs = &sigs[&variant];
        let signature = sig_docs.first().map(|s| s.trim_matches(|c| c == '`' || c == '.')).unwrap_or("");
        let signature = signature.split("`. (").next().unwrap_or(signature);
        let doc = long.get(&name).or_else(|| long.get(&format!("{name}_"))).map(|d| d.join("\n")).unwrap_or_default();
        let format = format!("{:?}", op.format());
        writeln!(
            out,
            "    OpcodeInfo {{ name: {name:?}, signature: {signature:?}, format: {format:?}, doc: {doc:?}, \
             terminator: {}, branch: {}, call: {}, ret: {}, load: {}, store: {}, trap: {}, side_effects: {} }},",
            op.is_terminator(),
            op.is_branch(),
            op.is_call(),
            op.is_return(),
            op.can_load(),
            op.can_store(),
            op.can_trap(),
            op.other_side_effects(),
        )
        .unwrap();
    }
    out.push_str("];\n");
    out
}

fn humanize(camel: &str) -> String {
    let mut out = String::new();
    for (i, c) in camel.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            out.push(' ');
        }
        out.extend(c.to_lowercase());
    }
    out
}

fn type_docs(types_rs: &str) -> Vec<(String, String)> {
    let lines: Vec<&str> = types_rs.lines().collect();
    let mut out = Vec::new();
    for (i, line) in lines.iter().enumerate() {
        let Some(rest) = line.strip_prefix("pub const ") else { continue };
        let name = rest.split(':').next().unwrap().to_lowercase().replace("xn", "xN");
        out.push((name, doc_lines(&lines, i).join(" ")));
    }
    out
}

fn push_entry(out: &mut String, name: &str, doc: &str) {
    writeln!(out, "    NameInfo {{ name: {name:?}, doc: {doc:?} }},").unwrap();
}

fn generate_types() -> String {
    let docs = type_docs(&generated("types.rs"));
    let scalars = [
        types::I8, types::I16, types::I32, types::I64, types::I128,
        types::F16, types::F32, types::F64, types::F128,
    ];
    let mut known: Vec<Type> = scalars.to_vec();
    for lane in scalars {
        let mut lanes = 2;
        while lanes <= 256 {
            known.extend(lane.by(lanes).filter(|v| v.bits() <= 512));
            lanes *= 2;
        }
    }
    let listed: Vec<&str> = docs.iter().map(|(n, _)| n.as_str()).collect();
    for ty in known {
        assert!(listed.contains(&ty.to_string().as_str()), "type `{ty}` missing from cranelift-codegen-meta");
    }

    let mut out = String::new();
    out.push_str("// @generated by `cargo run -p xtask -- gen-types` from cranelift 0.136.2; do not edit.\n\n");
    out.push_str("use super::NameInfo;\n\npub static TYPES: &[NameInfo] = &[\n");
    for (name, doc) in &docs {
        push_entry(&mut out, name, doc);
    }
    out.push_str("];\n");
    out
}

fn call_conv_name(cc: CallConv) -> &'static str {
    match cc {
        CallConv::Fast => "fast",
        CallConv::Tail => "tail",
        CallConv::SystemV => "system_v",
        CallConv::WindowsFastcall => "windows_fastcall",
        CallConv::AppleAarch64 => "apple_aarch64",
        CallConv::Probestack => "probestack",
        CallConv::Winch => "winch",
        CallConv::PreserveAll => "preserve_all",
    }
}

fn generate_codes() -> String {
    let mut out = String::new();
    out.push_str("// @generated by `cargo run -p xtask -- gen-types` from cranelift 0.136.2; do not edit.\n\n");
    out.push_str("use super::NameInfo;\n\n");

    out.push_str("pub static INT_CC: &[NameInfo] = &[\n");
    for cc in IntCC::all() {
        push_entry(&mut out, &cc.to_string(), &humanize(&format!("{cc:?}")));
    }
    out.push_str("];\n\npub static FLOAT_CC: &[NameInfo] = &[\n");
    for cc in FloatCC::all() {
        push_entry(&mut out, &cc.to_string(), &humanize(&format!("{cc:?}")));
    }

    let trap_docs = [
        ("stk_ovf", "The current stack space was exhausted."),
        ("heap_oob", "A `heap_addr` instruction detected an out-of-bounds error."),
        ("int_ovf", "An integer arithmetic operation caused an overflow."),
        ("int_divz", "An integer division by zero."),
        ("bad_toint", "Failed float-to-int conversion."),
    ];
    let real: Vec<String> = TrapCode::non_user_traps().iter().map(|t| t.to_string()).collect();
    let mut listed: Vec<String> = trap_docs.iter().map(|(n, _)| n.to_string()).collect();
    let mut real_sorted = real.clone();
    real_sorted.sort();
    listed.sort();
    assert_eq!(real_sorted, listed, "trap codes drifted from cranelift-codegen");
    out.push_str("];\n\npub static TRAP_CODES: &[NameInfo] = &[\n");
    for (name, doc) in trap_docs {
        push_entry(&mut out, name, doc);
    }

    let mem_flags = [
        ("notrap", "The access cannot trap."),
        ("aligned", "The access is aligned to its natural size."),
        ("readonly", "The memory is read-only for the duration of the function."),
        ("little", "The access is little-endian."),
        ("big", "The access is big-endian."),
        ("can_move", "The load may be moved or deduplicated."),
    ];
    for (name, _) in mem_flags {
        assert_eq!(MemFlagsData::trusted().set_by_name(name), Ok(true), "memflag `{name}`");
    }
    out.push_str("];\n\npub static MEM_FLAGS: &[NameInfo] = &[\n");
    for (name, doc) in mem_flags {
        push_entry(&mut out, name, doc);
    }

    let conventions = [
        CallConv::Fast, CallConv::Tail, CallConv::SystemV, CallConv::WindowsFastcall,
        CallConv::AppleAarch64, CallConv::Probestack, CallConv::Winch, CallConv::PreserveAll,
    ];
    out.push_str("];\n\npub static CALL_CONVS: &[NameInfo] = &[\n");
    for cc in conventions {
        assert_eq!(cc.to_string(), call_conv_name(cc));
        push_entry(&mut out, call_conv_name(cc), &humanize(&format!("{cc:?}")));
    }
    out.push_str("];\n");
    out
}

fn main() {
    let tables = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/tables");
    match std::env::args().nth(1).as_deref() {
        Some("gen-opcodes") => fs::write(tables.join("opcodes.rs"), generate_opcodes()).unwrap(),
        Some("gen-types") => {
            fs::write(tables.join("types.rs"), generate_types()).unwrap();
            fs::write(tables.join("codes.rs"), generate_codes()).unwrap();
        }
        _ => {
            eprintln!("usage: cargo run -p xtask -- gen-opcodes | gen-types");
            std::process::exit(2);
        }
    }
}
