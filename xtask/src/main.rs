use std::collections::HashMap;
use std::fmt::Write;
use std::fs;
use std::path::PathBuf;

use cranelift_codegen::ir::Opcode;

fn doc_lines(lines: &[&str], end: usize) -> Vec<String> {
    let mut docs = Vec::new();
    for line in lines[..end].iter().rev() {
        match line.trim_start().strip_prefix("///") {
            Some(doc) => docs.push(doc.strip_prefix(' ').unwrap_or(doc).to_owned()),
            None => break,
        }
    }
    docs.reverse();
    docs
}

fn variant_docs(opcodes_rs: &str) -> HashMap<String, Vec<String>> {
    let lines: Vec<&str> = opcodes_rs.lines().collect();
    let start = lines.iter().position(|l| *l == "pub enum Opcode {").unwrap();
    let mut out = HashMap::new();
    for (i, line) in lines.iter().enumerate().skip(start + 1) {
        if *line == "}" {
            break;
        }
        let trimmed = line.trim_start();
        if trimmed.starts_with("///") || trimmed.starts_with("//") {
            continue;
        }
        let name: String = trimmed.chars().take_while(|c| c.is_alphanumeric()).collect();
        out.insert(name, doc_lines(&lines, i));
    }
    out
}

fn builder_docs(inst_builder_rs: &str) -> HashMap<String, Vec<String>> {
    let lines: Vec<&str> = inst_builder_rs.lines().collect();
    let mut out = HashMap::new();
    for (i, line) in lines.iter().enumerate() {
        let Some(rest) = line.strip_prefix("    fn ") else { continue };
        let name: String = rest.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
        let mut end = i;
        while end > 0 && lines[end - 1].trim_start().starts_with("#[") {
            end -= 1;
        }
        out.entry(name).or_insert_with(|| doc_lines(&lines, end));
    }
    out
}

fn generate() -> String {
    let scratch = std::env::temp_dir().join(format!("clif-lsp-xtask-{}", std::process::id()));
    fs::create_dir_all(&scratch).unwrap();
    cranelift_codegen_meta::generate_rust(&[], &scratch).unwrap();
    let sigs = variant_docs(&fs::read_to_string(scratch.join("opcodes.rs")).unwrap());
    let long = builder_docs(&fs::read_to_string(scratch.join("inst_builder.rs")).unwrap());
    fs::remove_dir_all(&scratch).unwrap();

    let mut out = String::new();
    out.push_str("// @generated by `cargo run -p xtask -- gen-opcodes` from cranelift 0.136.2; do not edit.\n\n");
    out.push_str("use super::OpcodeInfo;\n\npub static OPCODES: &[OpcodeInfo] = &[\n");
    let mut opcodes: Vec<Opcode> = Opcode::all().to_vec();
    opcodes.sort_by_key(|o| o.to_string());
    for op in opcodes {
        let name = op.to_string();
        let variant = format!("{op:?}");
        let sig_docs = &sigs[&variant];
        let signature = sig_docs.first().map(|s| s.trim_matches(|c| c == '`' || c == '.')).unwrap_or("");
        let signature = signature.split("`. (").next().unwrap_or(signature);
        let doc = long.get(&name).or_else(|| long.get(&format!("{name}_"))).map(|d| d.join("\n")).unwrap_or_default();
        let format = format!("{:?}", op.format());
        writeln!(
            out,
            "    OpcodeInfo {{ name: {name:?}, signature: {signature:?}, format: {format:?}, doc: {doc:?}, \
             terminator: {}, branch: {}, call: {}, ret: {}, load: {}, store: {}, trap: {}, side_effects: {} }},",
            op.is_terminator(),
            op.is_branch(),
            op.is_call(),
            op.is_return(),
            op.can_load(),
            op.can_store(),
            op.can_trap(),
            op.other_side_effects(),
        )
        .unwrap();
    }
    out.push_str("];\n");
    out
}

fn main() {
    match std::env::args().nth(1).as_deref() {
        Some("gen-opcodes") => {
            let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/tables/opcodes.rs");
            fs::write(path, generate()).unwrap();
        }
        _ => {
            eprintln!("usage: cargo run -p xtask -- gen-opcodes");
            std::process::exit(2);
        }
    }
}
